/**
 * Fetches the upstream shadcn source Cadence has to match, at a pinned commit:
 *
 *   .cache/shadcn/pin.json          the ref that was fetched
 *   .cache/shadcn/base/<id>.tsx     shadcn's Base UI source for that id
 *   upstream/manifest.json          exports + data-slot values per item (committed)
 *
 * The cache is disposable and gitignored; the manifest is committed, so
 * `parity:check` works offline. Cadence tracks two upstream layers:
 *
 *   - API:     `base` (the Base UI base) decides exports, props, and data-slot values
 *   - visuals: `new-york-v4` decides the Tailwind classes, recorded in the pin so a
 *              restyle is a deliberate act rather than drift
 *
 *   node scripts/sync-upstream.mjs             # use the ref already pinned
 *   node scripts/sync-upstream.mjs --latest    # resolve main again and re-pin
 *   node scripts/sync-upstream.mjs --ref <sha> # pin an exact commit
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { extractExports, extractSlots } from "./upstream-surface.mjs";

const root = process.cwd();
const args = process.argv.slice(2);
const flag = (name) => {
  const index = args.indexOf(`--${name}`);
  return index === -1 ? undefined : args[index + 1];
};

const REPOSITORY = "shadcn-ui/ui";
const BASE = "base";
const VISUAL_STYLE = "new-york-v4";
const RAW = `https://raw.githubusercontent.com/${REPOSITORY}`;
const SOURCE_PREFIX = `apps/v4/registry/bases/${BASE}`;

const cacheDir = path.join(root, ".cache", "shadcn");
const cacheSourceDir = path.join(cacheDir, BASE);
const pinPath = path.join(cacheDir, "pin.json");
const manifestPath = path.join(root, "upstream", "manifest.json");

const registry = JSON.parse(await readFile(path.join(root, "registry.json"), "utf8"));
const ids = registry.items.filter((item) => item.type === "registry:ui").map((item) => item.name);

async function readJson(file) {
  try {
    return JSON.parse(await readFile(file, "utf8"));
  } catch {
    return null;
  }
}

async function fetchText(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${response.statusText} for ${url}`);
  return response.text();
}

/** The ref to fetch: an explicit flag, the committed pin, or a fresh resolve of main. */
async function resolveRef() {
  const explicit = flag("ref");
  if (explicit) return { ref: explicit, date: null, source: "flag" };

  if (!args.includes("--latest")) {
    const pinned = (await readJson(pinPath)) ?? (await readJson(manifestPath))?.pin;
    if (pinned?.ref) return { ref: pinned.ref, date: pinned.date ?? null, source: "pin" };
  }

  const head = JSON.parse(await fetchText(`https://api.github.com/repos/${REPOSITORY}/commits/main?per_page=1`));
  const commit = Array.isArray(head) ? head[0] : head;
  if (!commit?.sha) throw new Error("could not resolve the head commit of main");
  return { ref: commit.sha, date: (commit.commit?.committer?.date ?? "").slice(0, 10) || null, source: "main" };
}

const pin = await resolveRef();
console.log(`• upstream ${REPOSITORY}@${pin.ref.slice(0, 12)} (${pin.source})`);

await mkdir(cacheSourceDir, { recursive: true });

const items = {};
const missing = [];

for (const id of ids) {
  const upstreamPath = `${SOURCE_PREFIX}/ui/${id}.tsx`;
  let source;
  try {
    source = await fetchText(`${RAW}/${pin.ref}/${upstreamPath}`);
  } catch (error) {
    missing.push(`${id}: ${error.message}`);
    continue;
  }
  await writeFile(path.join(cacheSourceDir, `${id}.tsx`), source);
  items[id] = { path: upstreamPath, exports: extractExports(source), slots: extractSlots(source) };
  console.log(`  ✓ ${id} — ${items[id].exports.length} exports, ${items[id].slots.length} slots`);
}

if (missing.length) {
  console.error(`Could not pin every item:\n${missing.map((line) => `  - ${line}`).join("\n")}`);
  process.exit(1);
}

const manifest = {
  $comment:
    "Generated by scripts/sync-upstream.mjs. `exports` and `slots` are shadcn's Base UI surface; parity:check fails when a local component is missing one.",
  registry: "shadcn",
  repository: `https://github.com/${REPOSITORY}`,
  primitiveBase: BASE,
  visualStyle: VISUAL_STYLE,
  pin: { ref: pin.ref, date: pin.date, syncedAt: new Date().toISOString().slice(0, 10) },
  items,
};

await mkdir(path.dirname(manifestPath), { recursive: true });
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(pinPath, `${JSON.stringify(manifest.pin, null, 2)}\n`);

console.log(`✓ upstream/manifest.json pinned to ${pin.ref.slice(0, 12)} (${Object.keys(items).length} items)`);
console.log("  next: pnpm registry:build && pnpm parity:check");
